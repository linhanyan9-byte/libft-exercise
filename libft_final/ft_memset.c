#include "libft.h"

void	*ft_memset(void *s, int c, size_t n)
{
	unsigned char	unsigned_c = (unsigned char)c;
	size_t			i;
	unsigned char	*str;

	str = (unsigned char *) s;
	i = 0;
	while (i < n)
	{
		str[i] = unsigned_c;
		i++;
	}
	return (s);
}
