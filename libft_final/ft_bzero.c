#include "libft.h"
void	ft_bzero(void *s, size_t n)
{
	size_t			i;
	unsigned char	*s1;

	s1 = (unsigned char *) s;
	i = 0;
	while (i < n)
	{
		s1[i] = '\0';
		i++;
	}
}
